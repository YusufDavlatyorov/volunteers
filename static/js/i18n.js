// Exposed so inline page scripts (e.g. the AI chat) can look up strings for
// dynamically-created elements without a second copy of the table.
window.T = T;

// Fill {name} placeholders from a data-i18n-args JSON object (e.g. the
// min_length of a server-rendered password error); unknown or malformed
// args leave the placeholder as-is.
function interpolate(text, argsJson) {
  if (!argsJson) return text;
  let args;
  try { args = JSON.parse(argsJson); } catch (e) { return text; }
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in args ? String(args[name]) : m));
}

function setLanguage(lang) {
  if (!T[lang]) lang = 'en';
  localStorage.setItem('gc-lang', lang);
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (T[lang][key]) el.textContent = interpolate(T[lang][key], el.getAttribute('data-i18n-args'));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (T[lang][key]) el.placeholder = T[lang][key];
  });
  // Attribute-only text: tooltip (title), image alt, aria-label. An element
  // may carry visible text (data-i18n) and one of these at the same time.
  [['data-i18n-title', 'title'], ['data-i18n-alt', 'alt'], ['data-i18n-aria', 'aria-label']].forEach(([attr, target]) => {
    document.querySelectorAll(`[${attr}]`).forEach(el => {
      const key = el.getAttribute(attr);
      if (T[lang][key]) el.setAttribute(target, interpolate(T[lang][key], el.getAttribute('data-i18n-args')));
    });
  });
  document.querySelectorAll('[data-i18n-tooltip]').forEach(el => {
    const key = el.getAttribute('data-i18n-tooltip');
    if (T[lang][key]) { el.setAttribute('data-tooltip', T[lang][key]); el.setAttribute('aria-label', T[lang][key]); }
  });
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  // Keep the responsive (stacked) data-table row labels in sync with the
  // translated column headers, so the mobile card view is localized too.
  document.querySelectorAll('table.data-table').forEach(table => {
    const heads = Array.from(table.querySelectorAll('thead th')).map(th => th.textContent.trim());
    table.querySelectorAll('tbody tr').forEach(tr => {
      Array.from(tr.children).forEach((td, i) => {
        if (heads[i]) td.setAttribute('data-label', heads[i]);
      });
    });
  });
}

document.addEventListener('DOMContentLoaded', () => {
  // Russian by default: the server pre-renders Russian text (<html lang="ru">,
  // server/i18n_prerender.py), so a first visit shows no language flash.
  const lang = localStorage.getItem('gc-lang') || 'ru';
  setLanguage(lang);
});
